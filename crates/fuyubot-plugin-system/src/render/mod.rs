//! 图像生成：把 [`CardData`] 渲染成一张 1400×800 的系统信息卡片（JPEG）。
//!
//! 方案借鉴 <https://github.com/thomasmost/hyper-render>：不装浏览器、不用 Node，
//! 直接「HTML + CSS → Blitz 布局 → Vello CPU 光栅化」，纯 Rust 一条链路。
//! 与 TS 版 `E:\Fuyu_TDBot\plugins\system`（`index.ts` + `system.vue` + satori + resvg）的
//! 对应关系：
//!
//! | TS 版（Vue + satori + resvg） | 这里（hyper-render + image） |
//! | --- | --- |
//! | `system.vue` 模板 → `satoriVue` | [`template::build_html`] 生成静态 HTML |
//! | satori 的 flex 布局子集 | Blitz（Stylo + Taffy）完整布局 |
//! | resvg 光栅化 SVG | Vello CPU 光栅化 |
//! | 背景图 + 白色蒙版（CSS） | [`compose::build_background`] 在 Rust 侧逐像素合成 |
//! | `<img>` 头像 | [`compose::paste_avatars`] 用 `image` 贴圆形头像 |
//!
//! 一张卡片分三层合成（从底到顶）：
//!
//! 1. [`compose::build_background`]：`linear-gradient(132.5deg,#ffffff,#ceeddb)` →
//!    背景图（若有）cover-fit 整幅叠加 → 白色蒙版（水平 alpha 1.0 → 0.09），
//!    得到一张**不透明** RGB 画布；
//! 2. [`template::render_layer`]：hyper-render 渲出 1400×800 的**透明** HTML 层
//!    （卡片、文字、进度条、胶囊、头像占位的渐变圆），[`compose::composite_layer`]
//!    按 alpha 合成到背景上；
//! 3. [`compose::paste_avatars`]：把机器人 / 管理员的照片 cover 裁成圆形贴进
//!    HTML 画好的白边圆环里，最后编码成 JPEG（quality 90）。
//!
//! hyper-render 0.2.2 不加载 `<img>`（含 data URI），所以头像与背景一律在 Rust 侧合成；
//! 渲染引擎内部有全局字体集合，出图走 [`template`] 里的串行锁。
//!
//! # 与 TS 版版面有意不同的地方
//!
//! 都是宿主能力或排版稳定性决定的，交付报告里也列了：
//!
//! - 背景图不再写死一个外链（`system.vue` 里的 bilibili 图），改由 [`Assets::background`]
//!   传入，取不到就只留渐变；白色蒙版的参数与 vue 完全一致（1.0 → 0.09 @ 70%）；
//! - 插件胶囊最多两行（vue 的 `flex-wrap` 不限行数），超出的折成 `+N`——卡片高度固定，
//!   两行之外一定会被裁，与其画出去不如显式收口；
//! - 插件面板底部补了「共 N 个插件」与 `Generated by FuyuBot` 两行小字：vue 里那块
//!   靠 `flex-grow` 撑满，插件少的时候会空出一大块，这里给它一个视觉落点；
//! - 管理员改成可选的 `[plugin.system] super_admin`：没配时 admin 面板显示配置提示，
//!   头像位置保留渐变占位（与 vue 的「必有 admin」不同，见 `core::model` 的说明）。

pub mod compose;
pub mod layout;
pub mod samples;
pub mod template;

use crate::core::model::{Assets, CardData};

/// 卡片设计尺寸（与 `system.vue` 的 `w-350 h-200` 按 4px 间距换算一致）。
pub const WIDTH: u32 = 1400;
pub const HEIGHT: u32 = 800;

/// 输出 JPEG 的质量（Telegram photo 上传用，90 足够且体积可控）。
pub const JPEG_QUALITY: u8 = 90;

/// 渲染失败的原因。
#[derive(Debug, thiserror::Error)]
pub enum Error {
    /// 布局 / 光栅化失败。
    #[error("渲染引擎报错: {0}")]
    Engine(String),
    /// 图片解码 / 合成 / 编码失败。
    #[error("图片处理失败: {0}")]
    Image(String),
}

/// 把一张卡片渲染成 JPEG 字节（1400×800）。
///
/// 取不到头像 / 背景图时只降级成占位，不会返回错误；只有渲染引擎或图片编解码
/// 真的失败才会走到 [`Error`]。
///
/// ```no_run
/// use system::core::model::{Assets, CardData};
/// use system::render::render_card;
///
/// let jpeg = render_card(&CardData::default(), &Assets::default()).expect("渲染失败");
/// std::fs::write("card.jpg", jpeg).expect("写文件失败");
/// ```
pub fn render_card(card: &CardData, assets: &Assets) -> Result<Vec<u8>, Error> {
    // 第 1 层：不透明背景（渐变 + 背景图 + 白色蒙版）。
    let mut canvas = compose::build_background(assets);

    // 第 2 层：hyper-render 的透明 HTML 层，按 alpha 叠到背景上。
    let layer = template::render_layer(card)?;
    compose::composite_layer(&mut canvas, &layer)?;

    // 第 3 层：圆形头像（照片缺失时保留 HTML 的渐变占位）。
    compose::paste_avatars(&mut canvas, assets);

    // 输出 JPEG：Telegram photo 用 RGB 即可。
    compose::encode_jpeg(&canvas, JPEG_QUALITY)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// 断言是合法 JPEG 并返回解码后的尺寸。
    fn jpeg_size(jpeg: &[u8]) -> (u32, u32) {
        assert!(jpeg.len() > 4, "JPEG 太短：{} bytes", jpeg.len());
        assert_eq!(&jpeg[..2], &[0xFF, 0xD8], "JPEG 必须以 SOI (FF D8) 开头");
        assert_eq!(
            &jpeg[jpeg.len() - 2..],
            &[0xFF, 0xD9],
            "JPEG 必须以 EOI (FF D9) 结尾"
        );
        let decoded = image::load_from_memory(jpeg).expect("JPEG 应当能解码");
        (decoded.width(), decoded.height())
    }

    #[test]
    fn renders_1400x800_jpeg() {
        let jpeg =
            render_card(&samples::sample_card(), &samples::sample_assets()).expect("渲染应当成功");
        let (width, height) = jpeg_size(&jpeg);
        assert_eq!(width, WIDTH);
        assert_eq!(height, HEIGHT);
        // 纯色 JPEG 会被压到很小；有内容的卡片正常在 100 KB 上下。
        assert!(jpeg.len() > 20_000, "JPEG 体积异常：{} bytes", jpeg.len());
    }

    #[test]
    fn renders_without_any_assets() {
        // 没有背景图、没有头像：仍然要出图（占位渐变圆 + 纯渐变背景）。
        let jpeg =
            render_card(&samples::sample_card(), &Assets::default()).expect("没有素材也要能出图");
        let (width, height) = jpeg_size(&jpeg);
        assert_eq!((width, height), (WIDTH, HEIGHT));
    }

    #[test]
    fn no_admin_card_still_renders() {
        let jpeg = render_card(&samples::sample_card_no_admin(), &samples::sample_assets())
            .expect("渲染应当成功");
        assert_eq!(jpeg_size(&jpeg), (WIDTH, HEIGHT));
    }

    #[test]
    fn extreme_data_does_not_panic() {
        // 1) 全空数据。
        let empty =
            render_card(&CardData::default(), &Assets::default()).expect("空数据也要能出图");
        assert_eq!(jpeg_size(&empty), (WIDTH, HEIGHT));

        // 2) 超长名字 + 一堆插件 + 塞满的磁盘。
        let mut card = samples::sample_card_long_names();
        card.bot.name = "名".repeat(400);
        card.bot.username = "u".repeat(400);
        card.tdlib.commit_hash = "f".repeat(400);
        card.plugins = (0..60)
            .map(|index| crate::core::model::PluginChip {
                name: format!("plugin_{index}_名字也很长很长"),
                state: "active".to_owned(),
            })
            .collect();
        card.disks = (0..8)
            .map(|index| crate::core::model::DiskUsage {
                label: format!("{index}"),
                used: "999.99 TB".to_owned(),
                total: "1000.00 TB".to_owned(),
                usage_percent: 99,
            })
            .collect();
        card.gauges = (0..6)
            .map(|index| crate::core::model::Gauge {
                label: format!("G{index}"),
                usage: 100,
            })
            .collect();
        let jpeg = render_card(&card, &samples::sample_assets()).expect("极端数据也要能出图");
        let (width, height) = jpeg_size(&jpeg);
        assert_eq!((width, height), (WIDTH, HEIGHT));

        // 3) 坏素材（不是图片）只降级，不失败。
        let broken = Assets {
            bot_photo: Some(vec![1, 2, 3, 4]),
            admin_photo: Some(Vec::new()),
            background: Some(vec![0xFF; 16]),
        };
        let jpeg = render_card(&samples::sample_card(), &broken).expect("坏素材也要能出图");
        assert_eq!(jpeg_size(&jpeg), (WIDTH, HEIGHT));
    }

    /// HTML 层本身也必须是 1400×800 的透明 PNG（合成层的尺寸前提）。
    #[test]
    fn html_layer_is_full_size_and_transparent() {
        let png = template::render_layer(&samples::sample_card()).expect("渲染应当成功");
        assert_eq!(&png[..8], b"\x89PNG\r\n\x1a\n", "PNG 签名不对");
        let layer = image::load_from_memory(&png).expect("PNG 应当能解码");
        assert_eq!((layer.width(), layer.height()), (WIDTH, HEIGHT));
        assert!(
            layer.color().has_alpha(),
            "卡片层必须带 alpha 通道，否则没法叠到背景上"
        );
    }
}
